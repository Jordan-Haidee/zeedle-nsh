export function parseLanguage(value: string): Language {
  return Object.prototype.hasOwnProperty.call(languageNames, value) ? (value as Language) : "en";
}

export function languageName(language: Language): string {
  return languageNames[language];
}

export function translate(language: Language, english: string): string {
  if (language === "en") return english;
  const template = translations[english]?.[language] ?? english;
  return template;
}
